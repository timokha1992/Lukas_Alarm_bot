# ПСЗСУ: отдельные городские формы немедленной угрозы.
# Они не используются фильтром MONITOR.
# ПСЗСУ: курс на Кременчук с предлогом «на» или без него.
# Реальные формы источника: «курс Кременчук», «курсом Кременчук»,
# «курс на Кременчук», «курсом на Кременчук».
# Этот блок относится только к ПСЗСУ.
KREMENCHUK_PSZSU_COURSE_TARGET_REGEX = (
    r"\\bкурс(?:ом)?\\s+(?:на\\s+)?"
    r"(?:кременчук(?:а|у|ом)?|кременчуці|"
    r"кременчуг(?:а|у|ом|е)?|"
    r"кремечук(?:а|у|ом)?|кремечуці|"
    r"кремычук(?:а|у|ом)?|кремычуці)\\b"
)

KREMENCHUK_PSZSU_CITY_FIRST_ALERT_REGEX = (
    r"(?:^|[^\w])\s*"
    r"(?:кременчук(?:а|у|ом)?|кременчуці|кременчуг(?:а|у|ом|е)?|"
    r"кремечук(?:а|у|ом)?|кремечуці|кремычук(?:а|у|ом)?|кремычуці)"
    r"\s*[-—:]?\s*"
    r"[^\n]{0,160}?"
    r"(?:в\s+укриття|терміново\s+в\s+укриття|"
    r"над\s+містом|в\s+районі\s+міста|"
    r"в\s+напрямку\s+міста|у\s+напрямку\s+міста|"
    r"у\s+вашому\s+напрямку|в\s+вашому\s+напрямку|"
    r"курс(?:ом)?\s+(?:на\s+)?місто|на\s+місто)"
)

KREMENCHUK_RESERVOIR_PATTERNS = (
    "кременчуцьке водосховище",
    "кременчуцького водосховища",
    "кременчуцьким водосховищем",
    "кременчугское водохранилище",
    "кременчугского водохранилища",
)

PSZSU_KREMENCHUK_CITY_REGEX = (
    r"(?:кременчук(?:а|у|ом)?|кременчуці|"
    r"кременчуг(?:а|у|ом|е)?|"
    r"кремечук(?:а|у|ом)?|кремечуці|кремечуком|"
    r"кремычук(?:а|у|ом)?|кремычуці|кремычуком)"
)

PSZSU_KREMENCHUK_MINUS_REGEX = (
    r"(?:"
    r"кременчуцьк(?:ий|ого|ому|им)\s+район(?:у|і|ом)?"
    r"|кременчуцьк(?:е|ого|им)\s+водосховищ(?:е|а|ем)"
    r"|повз\s+" + PSZSU_KREMENCHUK_CITY_REGEX
    + r"|довкола\s+" + PSZSU_KREMENCHUK_CITY_REGEX
    + r")"
)

# Граница слова после названия города: «Кременчуківка» — не Кременчук.
_PSZSU_CITY_END = r"(?![а-яіїєґ])"

# Архивная география PSZSU («между городами» и направления от города).
# Это внутренние промежуточные результаты: наружу они превращаются
# в единое действие ARCHIVE (см. classify_pszsu_kremenchuk_message).
# Перечисление через запятую («між Лубнами, Полтавою та Кременчуком»)
# тоже считается «между городами».
PSZSU_ARCHIVE_HIGH_REGEX = (
    r"між\s+(?!" + PSZSU_KREMENCHUK_CITY_REGEX + r"\b)[^;\n]{1,80}?\s+"
    + r"(?:та|і|й)\s+" + PSZSU_KREMENCHUK_CITY_REGEX + _PSZSU_CITY_END
    + r"|між\s+" + PSZSU_KREMENCHUK_CITY_REGEX + _PSZSU_CITY_END
    + r"\s+(?:та|і|й)\s+"
    + r"(?!" + PSZSU_KREMENCHUK_CITY_REGEX + r"\b)[^,;\n]{1,80}"
)

# Какую часть сообщения «съедает» архивная география при проверке,
# остался ли в тексте самостоятельный Кременчук. Для формы
# «між Кременчуком та X» убирается только «між Кременчуком та »,
# чтобы хвост («…, курс Кременчук») не пропал вместе с X.
PSZSU_ARCHIVE_HIGH_STRIP_REGEX = (
    r"між\s+(?!" + PSZSU_KREMENCHUK_CITY_REGEX + r"\b)[^;\n]{1,80}?\s+"
    + r"(?:та|і|й)\s+" + PSZSU_KREMENCHUK_CITY_REGEX + _PSZSU_CITY_END
    + r"|між\s+" + PSZSU_KREMENCHUK_CITY_REGEX + _PSZSU_CITY_END
    + r"\s+(?:та|і|й)\s+"
)

PSZSU_ARCHIVE_DIRECTION_REGEX = (
    r"(?:північніше|південніше|східніше|західніше)\s+"
    + PSZSU_KREMENCHUK_CITY_REGEX + _PSZSU_CITY_END
    + r"|на\s+(?:північ|південь|схід|захід)\s+від\s+"
    + PSZSU_KREMENCHUK_CITY_REGEX + _PSZSU_CITY_END
)

# «Кременчук та Полтава» / «Полтава і Кременчук»: Кременчук перечислен
# вместе с другим населённым пунктом. Реестра городов нет, поэтому
# «другой город» — это слово с заглавной буквы в оригинальном тексте
# (область «…щина/…ччина» и «БпЛА» городом не считаются).
# Применяется к ОРИГИНАЛЬНОМУ тексту (нужен регистр букв).
_PSZSU_CITY_CS = r"(?:м\.\s*)?(?i:" + PSZSU_KREMENCHUK_CITY_REGEX + r")" + _PSZSU_CITY_END

_PSZSU_OTHER_PLACE = (
    r"(?:м\.\s*)?"
    r"(?!(?i:" + PSZSU_KREMENCHUK_CITY_REGEX + r"))"
    r"(?!(?i:[\w'’\-]*(?:щин|ччин)))"
    r"(?!(?i:бпла))"
    r"(?-i:[А-ЯІЇЄҐ][А-ЯІЇЄҐа-яіїєґ'’\-]{2,})"
)

PSZSU_CITY_WITH_OTHER_PLACE_REGEX = (
    r"(?<![а-яіїєґА-ЯІЇЄҐ])" + _PSZSU_CITY_CS
    + r"\s+(?i:та|і|й|и)\s+" + _PSZSU_OTHER_PLACE
    + r"|" + _PSZSU_OTHER_PLACE
    + r"\s+(?i:та|і|й|и)\s+" + _PSZSU_CITY_CS
)

# Самостоятельное основание для тревоги Кременчуку (только PSZSU):
# явное направление/цель на город.
PSZSU_DIRECT_ALARM_REGEX = (
    r"(?<![а-яіїєґ])(?:"
    r"курс(?:ом)?\s+(?:на\s+)?|вектор(?:ом)?\s+(?:на\s+)?|"
    r"на\s+|до\s+|по\s+|для\s+|(?:у|в)\s+(?:напрямку|напрямі|бік)\s+"
    r")" + PSZSU_KREMENCHUK_CITY_REGEX + _PSZSU_CITY_END
)


# --- Вынесено из функций bot.py (значения не менялись) ---
# normalize_pszsu_text: «м.» перед PSZSU-формой города.
PSZSU_NORMALIZE_MP_REGEX = r"(?<!\w)м\s*\.\s*(?=" + PSZSU_KREMENCHUK_CITY_REGEX + r"(?:\b|$))"
# pszsu_has_kremenchuk_outside_minus: самостоятельное (с границами слова) упоминание города.
PSZSU_STANDALONE_CITY_REGEX = r"(?<![а-яіїєґ])" + PSZSU_KREMENCHUK_CITY_REGEX + r"(?![а-яіїєґ])"


# --- Исключения «положение + курс» и «мимо города» (только PSZSU) ---
# Добавлены как НОВЫЕ константы; существующие правила выше не менялись.
#
# Слово-направление: «північ», «захід», «західний», «північно-західний»,
# «північно західний» (так пишет источник). Берутся ТОЛЬКО формы сторон света.
PSZSU_DIRECTION_WORD_REGEX = (
    r"(?:(?:північно|південно)[\s-]*)?(?:північн|південн|східн|західн)[а-яіїєґ]*"
    r"|північ|південь|схід|захід"
)

# Фраза-направление: одно слово или перечисление через «/» и «та»
# («західному/південно-західному»).
_PSZSU_DIRECTION_PHRASE = (
    r"((?:" + PSZSU_DIRECTION_WORD_REGEX + r")"
    r"(?:\s*(?:/|та)\s*(?:" + PSZSU_DIRECTION_WORD_REGEX + r"))*)"
)

# Положение относительно города в предложном падеже: «на півночі від
# Кременчука», «на північному сході від Кременчука». (Форма винительного
# «на північ від Кременчука» уже есть в PSZSU_ARCHIVE_DIRECTION_REGEX.)
# Группа 1 - сектор положения.
PSZSU_POSITION_LOCATIVE_REGEX = (
    r"на\s+(північному\s+сході|північному\s+заході|південному\s+сході"
    r"|південному\s+заході|півночі|півдні|сході|заході)\s+від\s+"
    + PSZSU_KREMENCHUK_CITY_REGEX + _PSZSU_CITY_END
)

# Явный курс движения. Группа 1 - фраза-направление. Не учитываются формы
# «з/зі/із ...» (откуда), только куда.
PSZSU_COURSE_PHRASE_REGEXES = (
    # «курс на захід», «курсом на південь»
    r"курс(?:ом)?\s+на\s+" + _PSZSU_DIRECTION_PHRASE + r"(?![а-яіїєґ])",
    # «курс — західний», «курсом західним», «курс північно західний»
    r"курс(?:ом)?\s*[-—–:]?\s*" + _PSZSU_DIRECTION_PHRASE,
    # «західним курсом»
    _PSZSU_DIRECTION_PHRASE + r"\s+курсом",
    # «у західному напрямку», «на північно-західний напрямок»
    r"(?<!з\s)(?<!зі\s)(?<!із\s)(?:у|в|на)\s+" + _PSZSU_DIRECTION_PHRASE
    + r"\s+напрям[а-яіїєґ]*",
    # «північно-західним напрямком»
    _PSZSU_DIRECTION_PHRASE + r"\s+напрямком",
)

# Объект «мимо города» / «довкола города» без самостоятельного основания
# для тревоги: сообщение не ALERT, но упоминает город, поэтому идёт в картотеку.
PSZSU_PASS_BY_CITY_REGEX = (
    r"(?:повз|довкола)\s+" + PSZSU_KREMENCHUK_CITY_REGEX + _PSZSU_CITY_END
)


# --- Явная отмена / снятие угрозы (только PSZSU) ---
# Ответ канала на собственный пост может отменять прежнюю угрозу: «відбій», «загроза минула»,
# «більше не прямує на Кременчук», «не на Кременчук». Такое предложение само по себе не является
# основанием для тревоги: город в нём сохраняется в картотеке, ALERT требует отдельного
# предложения с прямым основанием. Список узкий и явный (широких эвристик нет).
PSZSU_CANCEL_REGEX = (
    r"відбій|відбою|скасован|скасува"
    r"|загроз[а-яіїєґ]*\s+(?:\S+\s+){0,3}?(?:минул[а-яіїєґ]*|зникл[а-яіїєґ]*|знят[а-яіїєґ]*)"
    r"|(?:минул[а-яіїєґ]*|знят[а-яіїєґ]*)\s+загроз"
    r"|(?:немає|нема|не\s+буде)\s+(?:\S+\s+){0,2}?загроз"
    r"|загроз[а-яіїєґ]*\s+(?:\S+\s+){0,2}?(?:немає|нема)"
    r"|не\s+загрожу[а-яіїєґ]*"
    r"|більше\s+не\s+(?:пряму[а-яіїєґ]*|загрожу[а-яіїєґ]*|летить|йде|на\s)"
    r"|(?<![а-яіїєґ])не\s+(?:прямує|летить|йде|рухається)\s+(?:на|до)\s"
    r"|(?<![а-яіїєґ])не\s+(?:на|до|для)\s+" + PSZSU_KREMENCHUK_CITY_REGEX + _PSZSU_CITY_END
)
