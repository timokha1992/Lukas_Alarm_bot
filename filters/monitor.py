# --- Пара «Кременчук + другой город» (has_monitor_city_with_other_place) ---
# Независимая копия того же шаблона, который PSZSU использует у себя
# (раньше MONITOR брал PSZSU_CITY_WITH_OTHER_PLACE_REGEX из общего файла).
# Значение не менялось. Копия сознательная: источники не должны делить конфигурацию.
_OTHER_PLACE_CITY_REGEX = (
    r"(?:кременчук(?:а|у|ом)?|кременчуці|"
    r"кременчуг(?:а|у|ом|е)?|"
    r"кремечук(?:а|у|ом)?|кремечуці|кремечуком|"
    r"кремычук(?:а|у|ом)?|кремычуці|кремычуком)"
)

# Граница слова после названия города: «Кременчуківка» — не Кременчук.
_OTHER_PLACE_CITY_END = r"(?![а-яіїєґ])"

# «Кременчук та Полтава» / «Полтава і Кременчук»: Кременчук перечислен
# вместе с другим населённым пунктом. Реестра городов нет, поэтому
# «другой город» — это слово с заглавной буквы в оригинальном тексте
# (область «…щина/…ччина» и «БпЛА» городом не считаются).
# Применяется к ОРИГИНАЛЬНОМУ тексту (нужен регистр букв).
_OTHER_PLACE_CITY_CS = r"(?:м\.\s*)?(?i:" + _OTHER_PLACE_CITY_REGEX + r")" + _OTHER_PLACE_CITY_END

_OTHER_PLACE_NAME = (
    r"(?:м\.\s*)?"
    r"(?!(?i:" + _OTHER_PLACE_CITY_REGEX + r"))"
    r"(?!(?i:[\w'’\-]*(?:щин|ччин)))"
    r"(?!(?i:бпла))"
    r"(?-i:[А-ЯІЇЄҐ][А-ЯІЇЄҐа-яіїєґ'’\-]{2,})"
)

MONITOR_CITY_WITH_OTHER_PLACE_REGEX = (
    r"(?<![а-яіїєґА-ЯІЇЄҐ])" + _OTHER_PLACE_CITY_CS
    + r"\s+(?i:та|і|й|и)\s+" + _OTHER_PLACE_NAME
    + r"|" + _OTHER_PLACE_NAME
    + r"\s+(?i:та|і|й|и)\s+" + _OTHER_PLACE_CITY_CS
)


